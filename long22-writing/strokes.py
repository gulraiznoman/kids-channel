def length(poly):
    return sum(math.hypot(b[0] - a[0], b[1] - a[1]) for a, b in zip(poly, poly[1:]))


def partial(strokes, f):
    """first fraction f of the strokes, by length. returns (polylines, tip point)"""
    total = sum(length(p) for p in strokes)
    left, out, tip = f * total, [], strokes[0][0]
    for p in strokes:
        if left <= 0:
            break
        L = length(p)
        if left >= L:
            out.append(p)
            left -= L
            tip = p[-1]
            continue
        pts, run = [p[0]], 0
        for a, b in zip(p, p[1:]):
            s = math.hypot(b[0] - a[0], b[1] - a[1])
            if run + s >= left:
                k = (left - run) / (s or 1)
                tip = (a[0] + (b[0] - a[0]) * k, a[1] + (b[1] - a[1]) * k)
                pts.append(tip)
                break
            pts.append(b)
            run += s
        out.append(pts)
        left = 0
    return out, tip
